%% Overlay Tobii UCS gaze points on the UR5e/CoppeliaSim trajectory.
%
% Inputs:
%   tobii_fixed_adm_2d_random_shape_d100.csv
%     Left/right gaze points in Tobii User Coordinate System (UCS) [mm],
%     display-area coordinates, and validity flags.
%   ur5e_fixed_adm_2d_random_shape_d100.csv
%     End-effector trajectory in the CoppeliaSim x-y frame [m].
%
% Output:
%   One spatial plot containing the robot trajectory, combined valid gaze,
%   I-VT fixation centres, and vectors between consecutive fixations in the
%   CoppeliaSim x-y frame. A second figure contains separate velocity-vector
%   and force-vector plots along the robot path. A third figure shows the
%   fixation-direction similarity with mean force and mean velocity during each
%   complete interval between consecutive fixations. fixation_table,
%   gaze_sample_results, and similarity_table remain in the workspace. No input
%   data is modified.
%
% Assumptions:
%   The CoppeliaSim view is orthographic, unrotated, and fixed during data
%   collection. The view zoom is adjusted so a 1 cm robot motion appears as
%   1 cm on the physical display. Tobii UCS +x/+y are aligned with and point
%   in the same directions as CoppeliaSim +x/+y. The Tobii UCS z component
%   is not used because the displayed shape lies in the CoppeliaSim x-y
%   plane. Raw gaze is expected to form a band around the robot trajectory
%   rather than coincide sample-for-sample with it.
%
% User settings:
%   alignment_mode selects either an approximate data-center translation or
%   a calibrated manual reference pair. Use "manual_reference" for absolute
%   spatial interpretation after measuring one corresponding point. The I-VT
%   velocity and duration thresholds control fixation classification. The force
%   and velocity averaging interval is defined by each fixation transition.

clear;
close all;
clc;

%% User Settings
script_directory = fileparts(mfilename('fullpath'));
gaze_csv_file = fullfile(script_directory, ...
    '..', 'data', 'raw_data', ...
    'tobii_fixed_adm_2d_random_shape_d100.csv');
robot_csv_file = fullfile(script_directory, ...
    '..', 'data', 'raw_data', ...
    'ur5e_fixed_adm_2d_random_shape_d100.csv');

% TODO physical screen motion divided by robot motion [unitless], must be > 0.
% Keep at 1.0 while the CoppeliaSim view is adjusted to physical 1:1 scale.
screen_motion_per_robot_motion = 1.0;

% TODO Tobii UCS axis signs in CoppeliaSim [unitless], each must be -1 or +1.
% The current aligned setup uses the same positive directions on both axes.
tobii_to_coppelia_axis_sign = [1.0, 1.0];

% TODO translation method: "data_centers" or "manual_reference".
% "data_centers" makes the plot immediately usable but removes the mean
% gaze-to-robot offset. It is not an absolute spatial calibration.
alignment_mode = "manual_reference";

% TODO one corresponding Tobii/CoppeliaSim point used only when
% alignment_mode="manual_reference". Enter finite [x, y] values in [mm]
% and [m], respectively.
manual_tobii_reference_xy_mm = [-20.713572, 181.247559];  % mm TODO
manual_coppelia_reference_xy_m = [-0.014000, -0.650000];  % m

% TODO true excludes gaze estimates outside normalized display [0, 1]^2.
plot_only_on_display_gaze = true;

% TODO raw gaze marker size [points^2], recommended range: 2 to 20.
gaze_marker_size = 8;

% TODO I-VT angular-velocity threshold [deg/s]. Recommended range: 20 to 70.
velocity_threshold_deg_s = 20.0;

% TODO minimum retained fixation duration [s]. Current value: 0.050 s.
minimum_fixation_duration_s = 0.060;

% TODO fixation-centre marker area [points^2], recommended range: 20 to 100.
fixation_marker_size = 50;

% TODO plot one robot vector every N samples. Recommended range: 10 to 100.
robot_vector_stride = 25;

% TODO robot-force axis signs in CoppeliaSim, each must be -1 or +1.
% The current robot and CoppeliaSim frames have the same x-y directions.
robot_force_to_coppelia_axis_sign = [1.0, 1.0];

% TODO MATLAB quiver display factor [unitless], recommended range: 0.2 to 1.
% Vector components retain their m/s and N values; the factor controls only
% their displayed arrow lengths on axes whose position units are metres.
robot_quiver_auto_scale_factor = 0.8;

% TODO add to gaze/fixation times to align them with robot time [s].
% Positive values move fixation transitions later on the robot timeline.
gaze_to_robot_time_offset_s = 0.0;

% TODO minimum robot samples required in each fixation transition [count], >= 1.
minimum_robot_samples_per_transition = 3;

% TODO reject nearly zero vectors before unit normalization.
minimum_fixation_displacement_m = 1e-6;  % [m], must be > 0
minimum_mean_force_n = 0.1;  % [N], must be > 0
minimum_mean_velocity_m_s = 1e-4;  % [m/s], must be > 0

if screen_motion_per_robot_motion <= 0
    error('screen_motion_per_robot_motion must be positive.');
end
if any(abs(tobii_to_coppelia_axis_sign) ~= 1)
    error('Each Tobii-to-CoppeliaSim axis sign must be -1 or +1.');
end
if velocity_threshold_deg_s <= 0
    error('velocity_threshold_deg_s must be positive.');
end
if minimum_fixation_duration_s < 0
    error('minimum_fixation_duration_s cannot be negative.');
end
if robot_vector_stride < 1 || robot_vector_stride ~= floor(robot_vector_stride)
    error('robot_vector_stride must be a positive integer.');
end
if any(abs(robot_force_to_coppelia_axis_sign) ~= 1)
    error('Each robot-force-to-CoppeliaSim axis sign must be -1 or +1.');
end
if robot_quiver_auto_scale_factor <= 0
    error('robot_quiver_auto_scale_factor must be positive.');
end
if minimum_robot_samples_per_transition < 1 || ...
        minimum_robot_samples_per_transition ~= ...
        floor(minimum_robot_samples_per_transition)
    error(['minimum_robot_samples_per_transition must be a positive ', ...
        'integer.']);
end
if minimum_fixation_displacement_m <= 0 || ...
        minimum_mean_force_n <= 0 || minimum_mean_velocity_m_s <= 0
    error('Similarity vector-norm thresholds must be positive.');
end

%% Load and combine valid Tobii gaze points
gaze_table = readtable(gaze_csv_file, ...
    'Delimiter', ',', ...
    'ReadVariableNames', true, ...
    'VariableNamingRule', 'preserve', ...
    'TextType', 'string');

required_gaze_variables = {
    'system_time_stamp'
    'left_gaze_origin_in_user_coordinate_system'
    'left_gaze_origin_validity'
    'left_gaze_point_in_user_coordinate_system'
    'left_gaze_point_on_display_area'
    'left_gaze_point_validity'
    'right_gaze_origin_in_user_coordinate_system'
    'right_gaze_origin_validity'
    'right_gaze_point_in_user_coordinate_system'
    'right_gaze_point_on_display_area'
    'right_gaze_point_validity'
    };
require_table_variables( ...
    gaze_table, required_gaze_variables, 'Tobii CSV');

left_gaze_ucs_mm = parse_vector_column( ...
    gaze_table.left_gaze_point_in_user_coordinate_system, 3);
right_gaze_ucs_mm = parse_vector_column( ...
    gaze_table.right_gaze_point_in_user_coordinate_system, 3);
left_gaze_origin_ucs_mm = parse_vector_column( ...
    gaze_table.left_gaze_origin_in_user_coordinate_system, 3);
right_gaze_origin_ucs_mm = parse_vector_column( ...
    gaze_table.right_gaze_origin_in_user_coordinate_system, 3);
left_display_gaze = parse_vector_column( ...
    gaze_table.left_gaze_point_on_display_area, 2);
right_display_gaze = parse_vector_column( ...
    gaze_table.right_gaze_point_on_display_area, 2);

left_point_valid = get_numeric_column( ...
    gaze_table.left_gaze_point_validity) == 1;
right_point_valid = get_numeric_column( ...
    gaze_table.right_gaze_point_validity) == 1;
left_origin_valid = get_numeric_column( ...
    gaze_table.left_gaze_origin_validity) == 1;
right_origin_valid = get_numeric_column( ...
    gaze_table.right_gaze_origin_validity) == 1;

system_time_us = get_numeric_column(gaze_table.system_time_stamp);
first_timestamp_idx = find(isfinite(system_time_us), 1, 'first');
if isempty(first_timestamp_idx)
    error('The Tobii CSV contains no finite system timestamps.');
end
gaze_time_s = ...
    (system_time_us - system_time_us(first_timestamp_idx)) * 1e-6;

left_point_valid = left_point_valid & finite_rows(left_gaze_ucs_mm);
right_point_valid = right_point_valid & finite_rows(right_gaze_ucs_mm);

if plot_only_on_display_gaze
    left_point_valid = left_point_valid & ...
        point_is_on_display(left_display_gaze);
    right_point_valid = right_point_valid & ...
        point_is_on_display(right_display_gaze);
end

[left_gaze_direction, left_eye_valid] = calculate_eye_direction( ...
    left_gaze_origin_ucs_mm, left_gaze_ucs_mm, ...
    left_origin_valid, left_point_valid);
[right_gaze_direction, right_eye_valid] = calculate_eye_direction( ...
    right_gaze_origin_ucs_mm, right_gaze_ucs_mm, ...
    right_origin_valid, right_point_valid);

[combined_gaze_ucs_mm, combined_point_valid] = combine_valid_eye_points( ...
    left_gaze_ucs_mm, right_gaze_ucs_mm, ...
    left_eye_valid, right_eye_valid);
[combined_gaze_direction, combined_direction_valid] = ...
    combine_valid_eye_directions( ...
    left_gaze_direction, right_gaze_direction, ...
    left_eye_valid, right_eye_valid);
combined_gaze_valid = combined_point_valid & combined_direction_valid;
combined_gaze_ucs_mm(~combined_gaze_valid, :) = NaN;

if ~any(combined_gaze_valid)
    error('The Tobii CSV contains no valid gaze points for plotting.');
end

%% Detect I-VT fixations in Tobii gaze-direction space
angular_velocity_deg_s = calculate_angular_velocity( ...
    combined_gaze_direction, gaze_time_s, combined_gaze_valid);
fixation_candidate = combined_gaze_valid & ...
    isfinite(angular_velocity_deg_s) & ...
    angular_velocity_deg_s <= velocity_threshold_deg_s;

candidate_changes = diff(double([false; fixation_candidate; false]));
candidate_start_indices = find(candidate_changes == 1);
candidate_end_indices = find(candidate_changes == -1) - 1;

gaze_is_fixation = false(height(gaze_table), 1);
fixation_start_time_s = zeros(0, 1);
fixation_end_time_s = zeros(0, 1);
fixation_duration_s = zeros(0, 1);
fixation_mean_ucs_x_mm = zeros(0, 1);
fixation_mean_ucs_y_mm = zeros(0, 1);
fixation_mean_ucs_z_mm = zeros(0, 1);
fixation_number_of_samples = zeros(0, 1);

for candidate_idx = 1:numel(candidate_start_indices)
    start_idx = candidate_start_indices(candidate_idx);
    end_idx = candidate_end_indices(candidate_idx);
    candidate_duration_s = gaze_time_s(end_idx) - gaze_time_s(start_idx);

    if candidate_duration_s < minimum_fixation_duration_s
        continue;
    end

    fixation_rows = start_idx:end_idx;
    gaze_is_fixation(fixation_rows) = true;
    mean_fixation_ucs_mm = mean( ...
        combined_gaze_ucs_mm(fixation_rows, :), 1);

    fixation_start_time_s(end + 1, 1) = gaze_time_s(start_idx);
    fixation_end_time_s(end + 1, 1) = gaze_time_s(end_idx);
    fixation_duration_s(end + 1, 1) = candidate_duration_s;
    fixation_mean_ucs_x_mm(end + 1, 1) = mean_fixation_ucs_mm(1);
    fixation_mean_ucs_y_mm(end + 1, 1) = mean_fixation_ucs_mm(2);
    fixation_mean_ucs_z_mm(end + 1, 1) = mean_fixation_ucs_mm(3);
    fixation_number_of_samples(end + 1, 1) = numel(fixation_rows);
end

fixation_table = table( ...
    fixation_start_time_s, ...
    fixation_end_time_s, ...
    fixation_duration_s, ...
    fixation_mean_ucs_x_mm, ...
    fixation_mean_ucs_y_mm, ...
    fixation_mean_ucs_z_mm, ...
    fixation_number_of_samples, ...
    'VariableNames', { ...
    'start_time_s', ...
    'end_time_s', ...
    'duration_s', ...
    'mean_ucs_x_mm', ...
    'mean_ucs_y_mm', ...
    'mean_ucs_z_mm', ...
    'number_of_samples'});

gaze_classification = repmat("invalid_gaze", height(gaze_table), 1);
gaze_classification(combined_gaze_valid) = "non_fixation";
gaze_classification(gaze_is_fixation) = "fixation";
gaze_classification(combined_gaze_valid & ...
    ~isfinite(angular_velocity_deg_s)) = "unclassified_velocity";

gaze_sample_results = table( ...
    gaze_time_s, ...
    combined_gaze_ucs_mm(:, 1), ...
    combined_gaze_ucs_mm(:, 2), ...
    angular_velocity_deg_s, ...
    fixation_candidate, ...
    gaze_is_fixation, ...
    gaze_classification, ...
    'VariableNames', { ...
    'time_s', ...
    'gaze_ucs_x_mm', ...
    'gaze_ucs_y_mm', ...
    'angular_velocity_deg_s', ...
    'fixation_candidate', ...
    'is_fixation', ...
    'classification'});

%% Load the robot trajectory in the CoppeliaSim frame
robot_table = readtable(robot_csv_file, ...
    'Delimiter', ',', ...
    'ReadVariableNames', true, ...
    'VariableNamingRule', 'preserve', ...
    'TextType', 'string');

required_robot_variables = {
    'time_s'
    'coppeliasim_x_m'
    'coppeliasim_y_m'
    'Fx_filt_N'
    'Fy_filt_N'
    };
require_table_variables( ...
    robot_table, required_robot_variables, 'UR5e CSV');

robot_time_s = get_numeric_column(robot_table.time_s);
coppeliasim_x_m = get_numeric_column(robot_table.coppeliasim_x_m);
coppeliasim_y_m = get_numeric_column(robot_table.coppeliasim_y_m);
force_x_filtered_n = get_numeric_column(robot_table.Fx_filt_N);
force_y_filtered_n = get_numeric_column(robot_table.Fy_filt_N);

robot_sample_valid = isfinite(robot_time_s) & ...
    isfinite(coppeliasim_x_m) & isfinite(coppeliasim_y_m) & ...
    isfinite(force_x_filtered_n) & isfinite(force_y_filtered_n);
robot_time_s = robot_time_s(robot_sample_valid);
coppeliasim_x_m = coppeliasim_x_m(robot_sample_valid);
coppeliasim_y_m = coppeliasim_y_m(robot_sample_valid);
force_x_filtered_n = force_x_filtered_n(robot_sample_valid);
force_y_filtered_n = force_y_filtered_n(robot_sample_valid);

[robot_time_s, robot_sort_order] = sort(robot_time_s);
coppeliasim_x_m = coppeliasim_x_m(robot_sort_order);
coppeliasim_y_m = coppeliasim_y_m(robot_sort_order);
force_x_filtered_n = force_x_filtered_n(robot_sort_order);
force_y_filtered_n = force_y_filtered_n(robot_sort_order);

[robot_time_s, unique_time_indices] = unique(robot_time_s, 'stable');
coppeliasim_x_m = coppeliasim_x_m(unique_time_indices);
coppeliasim_y_m = coppeliasim_y_m(unique_time_indices);
force_x_filtered_n = force_x_filtered_n(unique_time_indices);
force_y_filtered_n = force_y_filtered_n(unique_time_indices);

coppeliasim_xy_m = [coppeliasim_x_m, coppeliasim_y_m];

if numel(robot_time_s) < 2
    error('The UR5e CSV contains fewer than two valid unique samples.');
end

coppeliasim_velocity_x_m_s = gradient(coppeliasim_x_m, robot_time_s);
coppeliasim_velocity_y_m_s = gradient(coppeliasim_y_m, robot_time_s);
force_x_coppeliasim_n = ...
    robot_force_to_coppelia_axis_sign(1) * force_x_filtered_n;
force_y_coppeliasim_n = ...
    robot_force_to_coppelia_axis_sign(2) * force_y_filtered_n;

%% Transform Tobii UCS millimetres into CoppeliaSim metres
% The current 1:1 physical display/robot scale reduces this conversion to
% millimetres-to-metres. Retaining the ratio in the formula makes a future
% deliberate change in CoppeliaSim zoom visible and adjustable.
coppeliasim_m_per_tobii_mm = ...
    1e-3 / screen_motion_per_robot_motion;

if alignment_mode == "data_centers"
    tobii_reference_xy_mm = mean( ...
        combined_gaze_ucs_mm(combined_gaze_valid, 1:2), 1);
    coppelia_reference_xy_m = mean(coppeliasim_xy_m, 1);
    alignment_description = ...
        'data-center translation (not absolute calibration)';
elseif alignment_mode == "manual_reference"
    if any(~isfinite(manual_tobii_reference_xy_mm)) || ...
            any(~isfinite(manual_coppelia_reference_xy_m))
        error(['Manual alignment requires finite values for ' ...
            'manual_tobii_reference_xy_mm and ' ...
            'manual_coppelia_reference_xy_m.']);
    end
    tobii_reference_xy_mm = manual_tobii_reference_xy_mm;
    coppelia_reference_xy_m = manual_coppelia_reference_xy_m;
    alignment_description = 'manual calibrated reference';
else
    error('alignment_mode must be "data_centers" or "manual_reference".');
end

gaze_displacement_ucs_mm = ...
    combined_gaze_ucs_mm(:, 1:2) - tobii_reference_xy_mm;
gaze_displacement_coppelia_m = ...
    gaze_displacement_ucs_mm .* ...
    tobii_to_coppelia_axis_sign .* ...
    coppeliasim_m_per_tobii_mm;
gaze_coppeliasim_xy_m = ...
    coppelia_reference_xy_m + gaze_displacement_coppelia_m;

fixation_ucs_xy_mm = [ ...
    fixation_table.mean_ucs_x_mm, ...
    fixation_table.mean_ucs_y_mm];
fixation_displacement_ucs_mm = ...
    fixation_ucs_xy_mm - tobii_reference_xy_mm;
fixation_displacement_coppelia_m = ...
    fixation_displacement_ucs_mm .* ...
    tobii_to_coppelia_axis_sign .* ...
    coppeliasim_m_per_tobii_mm;
fixation_coppeliasim_xy_m = ...
    coppelia_reference_xy_m + fixation_displacement_coppelia_m;

%% Plot gaze and consecutive I-VT fixation vectors over the robot trajectory
figure('Name', 'Tobii UCS gaze over UR5e trajectory', 'Color', 'w');
hold on;

plot( ...
    coppeliasim_xy_m(:, 1), ...
    coppeliasim_xy_m(:, 2), ...
    'Color', [0.20, 0.20, 0.20], ...
    'LineWidth', 1.5, ...
    'DisplayName', 'UR5e end-effector trajectory');

scatter( ...
    gaze_coppeliasim_xy_m(combined_gaze_valid, 1), ...
    gaze_coppeliasim_xy_m(combined_gaze_valid, 2), ...
    gaze_marker_size, ...
    [0.85, 0.10, 0.10], ...
    'filled', ...
    'DisplayName', 'Combined valid gaze points');

if height(fixation_table) >= 2
    fixation_vector_x_m = diff(fixation_coppeliasim_xy_m(:, 1));
    fixation_vector_y_m = diff(fixation_coppeliasim_xy_m(:, 2));
    quiver( ...
        fixation_coppeliasim_xy_m(1:end-1, 1), ...
        fixation_coppeliasim_xy_m(1:end-1, 2), ...
        fixation_vector_x_m, ...
        fixation_vector_y_m, ...
        0, ...
        'Color', [0.10, 0.55, 0.20], ...
        'LineWidth', 1.5, ...
        'MaxHeadSize', 0.6, ...
        'DisplayName', 'Direction to next fixation (saccade)');
end

if ~isempty(fixation_table)
    scatter( ...
        fixation_coppeliasim_xy_m(:, 1), ...
        fixation_coppeliasim_xy_m(:, 2), ...
        fixation_marker_size, ...
        [0.10, 0.45, 0.85], ...
        'filled', ...
        'MarkerEdgeColor', 'k', ...
        'DisplayName', 'I-VT fixation centres');
end

plot( ...
    coppelia_reference_xy_m(1), ...
    coppelia_reference_xy_m(2), ...
    'kx', ...
    'MarkerSize', 10, ...
    'LineWidth', 1.5, ...
    'DisplayName', 'Alignment reference');

grid on;
axis equal;
xlabel('CoppeliaSim x [m]');
ylabel('CoppeliaSim y [m]');
title({ ...
    'I-VT fixations over UR5e end-effector trajectory', ...
    sprintf('%s; %.1f deg/s, %.0f ms minimum', ...
    alignment_description, velocity_threshold_deg_s, ...
    minimum_fixation_duration_s * 1e3)});
legend('Location', 'best');

%% Plot robot velocity and force vectors along the trajectory
robot_vector_indices = (1:robot_vector_stride:numel(robot_time_s))';
coppeliasim_x_limits_m = [min(coppeliasim_x_m), max(coppeliasim_x_m)];
coppeliasim_y_limits_m = [min(coppeliasim_y_m), max(coppeliasim_y_m)];
x_margin_m = max(0.05 * diff(coppeliasim_x_limits_m), 0.005);
y_margin_m = max(0.05 * diff(coppeliasim_y_limits_m), 0.005);

figure('Name', 'UR5e velocity and force vectors', ...
    'Color', 'w');

subplot(1, 2, 1);
hold on;
plot( ...
    coppeliasim_x_m, ...
    coppeliasim_y_m, ...
    'Color', [0.70, 0.70, 0.70], ...
    'LineWidth', 1.5, ...
    'DisplayName', 'UR5e end-effector trajectory');
quiver( ...
    coppeliasim_x_m(robot_vector_indices), ...
    coppeliasim_y_m(robot_vector_indices), ...
    coppeliasim_velocity_x_m_s(robot_vector_indices), ...
    coppeliasim_velocity_y_m_s(robot_vector_indices), ...
    robot_quiver_auto_scale_factor, ...
    'Color', [0.10, 0.45, 0.85], ...
    'LineWidth', 1.0, ...
    'MaxHeadSize', 1.5, ...
    'DisplayName', 'Measured velocity');
grid on;
axis equal;
xlim(coppeliasim_x_limits_m + [-x_margin_m, x_margin_m]);
ylim(coppeliasim_y_limits_m + [-y_margin_m, y_margin_m]);
xlabel('CoppeliaSim x [m]');
ylabel('CoppeliaSim y [m]');
title('Velocity vectors along robot trajectory');
legend('Location', 'best');

subplot(1, 2, 2);
hold on;
plot( ...
    coppeliasim_x_m, ...
    coppeliasim_y_m, ...
    'Color', [0.70, 0.70, 0.70], ...
    'LineWidth', 1.5, ...
    'DisplayName', 'UR5e end-effector trajectory');
quiver( ...
    coppeliasim_x_m(robot_vector_indices), ...
    coppeliasim_y_m(robot_vector_indices), ...
    force_x_coppeliasim_n(robot_vector_indices), ...
    force_y_coppeliasim_n(robot_vector_indices), ...
    robot_quiver_auto_scale_factor, ...
    'Color', [0.85, 0.25, 0.10], ...
    'LineWidth', 1.0, ...
    'MaxHeadSize', 1.5, ...
    'DisplayName', 'Filtered force');
grid on;
axis equal;
xlim(coppeliasim_x_limits_m + [-x_margin_m, x_margin_m]);
ylim(coppeliasim_y_limits_m + [-y_margin_m, y_margin_m]);
xlabel('CoppeliaSim x [m]');
ylabel('CoppeliaSim y [m]');
title('Force vectors along robot trajectory');
legend('Location', 'best');

%% Compute fixation-transition similarity with force and velocity
% Transition i points from fixation i to fixation i+1. Its exact temporal
% interval begins when fixation i ends and ends when fixation i+1 starts.
transition_count = max(height(fixation_table) - 1, 0);
from_fixation_index = (1:transition_count)';
to_fixation_index = (2:(transition_count + 1))';

transition_start_gaze_time_s = fixation_table.end_time_s(1:end-1);
transition_end_gaze_time_s = fixation_table.start_time_s(2:end);
