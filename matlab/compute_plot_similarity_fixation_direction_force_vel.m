mean_force_norm_n = NaN(transition_count, 1);
mean_force_unit_xy = NaN(transition_count, 2);
fixation_force_similarity = NaN(transition_count, 1);
fixation_force_angle_deg = NaN(transition_count, 1);

mean_velocity_xy_m_s = NaN(transition_count, 2);
mean_velocity_norm_m_s = NaN(transition_count, 1);
mean_velocity_unit_xy = NaN(transition_count, 2);
fixation_velocity_similarity = NaN(transition_count, 1);
fixation_velocity_angle_deg = NaN(transition_count, 1);
robot_samples_in_transition = zeros(transition_count, 1);

for transition_idx = 1:transition_count
    if transition_duration_s(transition_idx) <= 0
        continue;
    end

    robot_transition_mask = ...
        robot_time_s >= transition_start_robot_time_s(transition_idx) & ...
        robot_time_s <= transition_end_robot_time_s(transition_idx);
    robot_samples_in_transition(transition_idx) = ...
        nnz(robot_transition_mask);

    if robot_samples_in_transition(transition_idx) < ...
            minimum_robot_samples_per_transition
        continue;
    end

    if fixation_transition_norm_m(transition_idx) < ...
            minimum_fixation_displacement_m
        continue;
    end

    fixation_unit_xy(transition_idx, :) = ...
        fixation_transition_xy_m(transition_idx, :) ./ ...
        fixation_transition_norm_m(transition_idx);

    mean_force_xy_n(transition_idx, :) = [ ...
        mean(force_x_coppeliasim_n(robot_transition_mask)), ...
        mean(force_y_coppeliasim_n(robot_transition_mask))];
    mean_force_norm_n(transition_idx) = hypot( ...
        mean_force_xy_n(transition_idx, 1), ...
        mean_force_xy_n(transition_idx, 2));

    if mean_force_norm_n(transition_idx) >= minimum_mean_force_n
        mean_force_unit_xy(transition_idx, :) = ...
            mean_force_xy_n(transition_idx, :) ./ ...
            mean_force_norm_n(transition_idx);
        fixation_force_similarity(transition_idx) = dot( ...
            fixation_unit_xy(transition_idx, :), ...
            mean_force_unit_xy(transition_idx, :));
        fixation_force_similarity(transition_idx) = max( ...
            -1.0, min(1.0, fixation_force_similarity(transition_idx)));
        fixation_force_angle_deg(transition_idx) = acosd( ...
            fixation_force_similarity(transition_idx));
    end

    mean_velocity_xy_m_s(transition_idx, :) = [ ...
        mean(coppeliasim_velocity_x_m_s(robot_transition_mask)), ...
        mean(coppeliasim_velocity_y_m_s(robot_transition_mask))];
    mean_velocity_norm_m_s(transition_idx) = hypot( ...
        mean_velocity_xy_m_s(transition_idx, 1), ...
        mean_velocity_xy_m_s(transition_idx, 2));

    if mean_velocity_norm_m_s(transition_idx) >= ...
            minimum_mean_velocity_m_s
        mean_velocity_unit_xy(transition_idx, :) = ...
            mean_velocity_xy_m_s(transition_idx, :) ./ ...
            mean_velocity_norm_m_s(transition_idx);
        fixation_velocity_similarity(transition_idx) = dot( ...
            fixation_unit_xy(transition_idx, :), ...
            mean_velocity_unit_xy(transition_idx, :));
        fixation_velocity_similarity(transition_idx) = max( ...
            -1.0, min(1.0, fixation_velocity_similarity(transition_idx)));
        fixation_velocity_angle_deg(transition_idx) = acosd( ...
            fixation_velocity_similarity(transition_idx));
    end
end

