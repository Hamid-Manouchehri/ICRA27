%% Analyze direct gaze/TCP path lead-lag and planar TCP curvature.
%
% Purpose:
%   For each gaze transition Fi->Fi+1, use the start of fixation Fi+1 as
%   the reference time. Project the Fi+1 centre onto the time-ordered TCP
%   path, determine when the TCP reaches that projected location, and compare
%   that reach time with the reference time. No lag scan or moving window is
%   used. The script also calculates filtered planar TCP curvature.
%
% Inputs:
%   *_fixation_transitions.csv from
%   compute_plot_similarity_fixation_direction_force_vel.m.
%   Matching raw ur5e_fixed_adm_2d_*.csv with synchronized time_s and
%   CoppeliaSim x-y TCP position [m]. The raw file is inferred from trial_id.
%
% Outputs:
%   lead_lag_table in the workspace and a *_gaze_tcp_path_lead_lag.csv file
%   in data/processed_data. Three figures show direct temporal/spatial lead,
%   spatial leader/follower locations, and curvature over the TCP path.
%   Input files are not modified.
%
% Sign convention:
%   gaze_lead_time = TCP reach time - fixation reference time.
%   gaze_lead_time > synchronous_time_tolerance_s  -> gaze leads TCP
%   gaze_lead_time < -synchronous_time_tolerance_s -> TCP leads gaze
%   otherwise                                        -> approximately synchronous
%
% Frames and units:
%   Fixation and TCP positions are in CoppeliaSim x-y [m]. Path progress is
%   arc length [m], time differences are [s], and curvature is [1/m].


clear;
close all;
clc;

script_directory = fileparts(mfilename('fullpath'));

%% User Settings
% TODO Select the fixation-transition CSV to analyze.
read_transition_csv_file = fullfile( ...
    script_directory, '..', 'data', 'processed_data', ...
    'ur5e_fixed_adm_2d_irregular_shape_2_d100_fixation_transitions.csv');

% TODO Time difference treated as approximately synchronous [s].
% Recommended range: 0.02 to 0.20 s.
synchronous_time_tolerance_s = 0.04;

% TODO Reject a fixation if its centre is farther than this distance from
% the filtered TCP path [m]. Recommended range: 0.005 to 0.050 m.
maximum_fixation_projection_distance_m = 0.020;

%% Fixed preprocessing values
% These values keep curvature and path projection numerically stable and do
% not normally need to be changed between experiments.
tcp_position_outlier_window_s = 0.02;
tcp_position_smoothing_window_s = 0.08;
minimum_curvature_speed_m_s = 0.002;
minimum_path_segment_length_m = 1e-5;
projection_tie_distance_m = 1e-3;

%% Validate settings
if synchronous_time_tolerance_s < 0
    error('synchronous_time_tolerance_s cannot be negative.');
end
if maximum_fixation_projection_distance_m <= 0
    error('maximum_fixation_projection_distance_m must be positive.');
end

%% Load fixation transitions and resolve related files
if ~isfile(read_transition_csv_file)
    error('Transition CSV not found: %s', read_transition_csv_file);
end

transition_table = readtable( ...
    read_transition_csv_file, ...
    'Delimiter', ',', ...
    'ReadVariableNames', true, ...
    'VariableNamingRule', 'preserve', ...
    'TextType', 'string');

required_transition_variables = {
    'trial_id'
    'transition_index'
    'from_fixation'
    'to_fixation'
    'end_time_s'
    'robot_end_time_s'
    'from_fixation_x_m'
    'from_fixation_y_m'
    'to_fixation_x_m'
    'to_fixation_y_m'
    'gaze_dx_m'
    'gaze_dy_m'
    };
require_table_variables( ...
    transition_table, ...
    required_transition_variables, ...
    'fixation-transition CSV');

trial_ids = unique(strtrim(string(transition_table.trial_id)));
trial_ids = trial_ids(~ismissing(trial_ids) & strlength(trial_ids) > 0);
if numel(trial_ids) ~= 1
    error('The transition CSV must contain exactly one nonempty trial_id.');
end
trial_id = trial_ids(1);

read_robot_csv_file = fullfile( ...
    script_directory, '..', 'data', 'raw_data', trial_id + ".csv");
if ~isfile(read_robot_csv_file)
    error('Matching raw robot CSV not found: %s', read_robot_csv_file);
end

write_lead_lag_csv_file = fullfile( ...
    script_directory, '..', 'data', 'processed_data', ...
    trial_id + "_gaze_tcp_path_lead_lag.csv");

%% Load and filter the raw CoppeliaSim TCP trajectory
robot_table = readtable( ...
    read_robot_csv_file, ...
    'Delimiter', ',', ...
    'ReadVariableNames', true, ...
    'VariableNamingRule', 'preserve', ...
    'TextType', 'string');

required_robot_variables = {
    'time_s'
    'coppeliasim_x_m'
    'coppeliasim_y_m'
    };
require_table_variables( ...
    robot_table, required_robot_variables, 'raw robot CSV');

robot_time_s = get_numeric_column(robot_table.time_s);
robot_x_coppelia_m = get_numeric_column(robot_table.coppeliasim_x_m);
robot_y_coppelia_m = get_numeric_column(robot_table.coppeliasim_y_m);

tcp = prepare_tcp_trajectory( ...
    robot_time_s, ...
    robot_x_coppelia_m, ...
    robot_y_coppelia_m, ...
    tcp_position_outlier_window_s, ...
    tcp_position_smoothing_window_s, ...
    minimum_curvature_speed_m_s);

tcp_segment_length_m = hypot( ...
    diff(tcp.x_filtered_m), diff(tcp.y_filtered_m));
tcp_segment_length_for_progress_m = tcp_segment_length_m;
tcp_segment_length_for_progress_m( ...
    tcp_segment_length_for_progress_m < ...
    minimum_path_segment_length_m) = 0.0;
tcp.path_progress_m = [ ...
    0.0; cumsum(tcp_segment_length_for_progress_m)];

if tcp.path_progress_m(end) <= 0
    error('The filtered TCP trajectory contains no measurable path motion.');
end

%% Extract gaze transitions and their reference times
transition_count = height(transition_table);

transition_index = get_numeric_column( ...
    transition_table.transition_index);
from_fixation = get_numeric_column(transition_table.from_fixation);
to_fixation = get_numeric_column(transition_table.to_fixation);
from_fixation_x_m = get_numeric_column( ...
    transition_table.from_fixation_x_m);
from_fixation_y_m = get_numeric_column( ...
    transition_table.from_fixation_y_m);
to_fixation_x_m = get_numeric_column( ...
    transition_table.to_fixation_x_m);
to_fixation_y_m = get_numeric_column( ...
    transition_table.to_fixation_y_m);

% end_time_s is the start time of fixation Fi+1 in the synchronized gaze
% timeline. robot_end_time_s is that same event mapped to the robot timeline.
gaze_reference_time_s = get_numeric_column(transition_table.end_time_s);
tcp_reference_time_s = get_numeric_column( ...
    transition_table.robot_end_time_s);

gaze_dx_m = get_numeric_column(transition_table.gaze_dx_m);
gaze_dy_m = get_numeric_column(transition_table.gaze_dy_m);
gaze_displacement_m = hypot(gaze_dx_m, gaze_dy_m);

gaze_unit_x = NaN(transition_count, 1);
gaze_unit_y = NaN(transition_count, 1);
valid_gaze_displacement = ...
    isfinite(gaze_displacement_m) & ...
    gaze_displacement_m > 0;
gaze_unit_x(valid_gaze_displacement) = ...
    gaze_dx_m(valid_gaze_displacement) ./ ...
    gaze_displacement_m(valid_gaze_displacement);
gaze_unit_y(valid_gaze_displacement) = ...
    gaze_dy_m(valid_gaze_displacement) ./ ...
    gaze_displacement_m(valid_gaze_displacement);

reference_tcp_x_m = interpolate_without_extrapolation( ...
    tcp.time_s, tcp.x_filtered_m, tcp_reference_time_s);
reference_tcp_y_m = interpolate_without_extrapolation( ...
    tcp.time_s, tcp.y_filtered_m, tcp_reference_time_s);
reference_tcp_path_progress_m = interpolate_without_extrapolation( ...
    tcp.time_s, tcp.path_progress_m, tcp_reference_time_s);
reference_tcp_speed_m_s = interpolate_without_extrapolation( ...
    tcp.time_s, tcp.speed_m_s, tcp_reference_time_s);
reference_tcp_curvature_1_m = interpolate_without_extrapolation( ...
    tcp.time_s, tcp.curvature_1_m, tcp_reference_time_s);
reference_tcp_signed_curvature_1_m = ...
    interpolate_without_extrapolation( ...
    tcp.time_s, tcp.signed_curvature_1_m, tcp_reference_time_s);

%% Compare each fixation target with TCP progress at its reference time
projected_fixation_x_m = NaN(transition_count, 1);
projected_fixation_y_m = NaN(transition_count, 1);
fixation_path_progress_m = NaN(transition_count, 1);
fixation_projection_distance_m = NaN(transition_count, 1);
tcp_reach_time_s = NaN(transition_count, 1);
gaze_lead_time_s = NaN(transition_count, 1);
gaze_spatial_lead_m = NaN(transition_count, 1);

leader_follower = repmat("not_valid", transition_count, 1);
analysis_valid = false(transition_count, 1);
analysis_status = repmat("not_evaluated", transition_count, 1);

for transition_idx = 1:transition_count
    if ~isfinite(tcp_reference_time_s(transition_idx))  % reject if invalid
        analysis_status(transition_idx) = "invalid_reference_time";
        continue;
    end

    if ~isfinite(reference_tcp_path_progress_m(transition_idx))
        analysis_status(transition_idx) = ...
            "reference_time_outside_tcp_recording";
        continue;
    end

    fixation_target_xy_m = [ ...
        to_fixation_x_m(transition_idx), ...
        to_fixation_y_m(transition_idx)];
    if any(~isfinite(fixation_target_xy_m))
        analysis_status(transition_idx) = "invalid_fixation_position";
        continue;
    end

    [projected_fixation_xy_m, ...
        fixation_path_progress_m(transition_idx), ...
        tcp_reach_time_s(transition_idx), ...
        fixation_projection_distance_m(transition_idx)] = ...
        project_point_to_timed_path( ...
        fixation_target_xy_m, ...
        tcp.time_s, ...
        tcp.x_filtered_m, ...
        tcp.y_filtered_m, ...
        tcp.path_progress_m, ...
        tcp_reference_time_s(transition_idx), ...
        minimum_path_segment_length_m, ...
        projection_tie_distance_m);

    projected_fixation_x_m(transition_idx) = ...
        projected_fixation_xy_m(1);
    projected_fixation_y_m(transition_idx) = ...
        projected_fixation_xy_m(2);

    if ~isfinite(tcp_reach_time_s(transition_idx))
        analysis_status(transition_idx) = "no_valid_tcp_path_segment";
        continue;
    end

    gaze_lead_time_s(transition_idx) = ...
        tcp_reach_time_s(transition_idx) - ...
        tcp_reference_time_s(transition_idx);
    gaze_spatial_lead_m(transition_idx) = ...
        fixation_path_progress_m(transition_idx) - ...
        reference_tcp_path_progress_m(transition_idx);

    if fixation_projection_distance_m(transition_idx) > ...
            maximum_fixation_projection_distance_m
        analysis_status(transition_idx) = ...
            "fixation_too_far_from_tcp_path";
        continue;
    end

    if gaze_lead_time_s(transition_idx) > ...
            synchronous_time_tolerance_s
        leader_follower(transition_idx) = "gaze_leads_tcp";
    elseif gaze_lead_time_s(transition_idx) < ...
            -synchronous_time_tolerance_s
        leader_follower(transition_idx) = "tcp_leads_gaze";
    else
        leader_follower(transition_idx) = ...
            "approximately_synchronous";
    end

    analysis_valid(transition_idx) = true;
    analysis_status(transition_idx) = "accepted";
end

