    to_fixation_x_m, ...
    to_fixation_y_m, ...
    gaze_dx_m, ...
    gaze_dy_m, ...
    gaze_displacement_m, ...
    gaze_unit_x, ...
    gaze_unit_y, ...
    reference_tcp_x_m, ...
    reference_tcp_y_m, ...
    reference_tcp_path_progress_m, ...
    reference_tcp_speed_m_s, ...
    reference_tcp_curvature_1_m, ...
    reference_tcp_signed_curvature_1_m, ...
    projected_fixation_x_m, ...
    projected_fixation_y_m, ...
    fixation_path_progress_m, ...
    fixation_projection_distance_m, ...
    tcp_reach_time_s, ...
    gaze_lead_time_s, ...
    gaze_spatial_lead_m, ...
    lead_lag_method, ...
    leader_follower, ...
    analysis_valid, ...
    analysis_status, ...
    synchronous_time_tolerance_column_s, ...
    maximum_projection_distance_column_m, ...
    'VariableNames', { ...
