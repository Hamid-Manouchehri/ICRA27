    'calibration_id', ...
    'transition_index', ...
    'from_fixation', ...
    'to_fixation', ...
    'gaze_reference_time_s', ...
    'tcp_reference_time_s', ...
    'from_fixation_x_m', ...
    'from_fixation_y_m', ...
    'to_fixation_x_m', ...
    'to_fixation_y_m', ...
    'gaze_dx_m', ...
    'gaze_dy_m', ...
    'gaze_displacement_m', ...
    'gaze_unit_x', ...
    'gaze_unit_y', ...
    'reference_tcp_x_m', ...
    'reference_tcp_y_m', ...
