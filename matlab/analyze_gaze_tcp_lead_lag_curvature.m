%% Analyze gaze-transition/TCP lead-lag and planar TCP curvature.
%
% Purpose:
%   For each gaze transition Fi->Fi+1, use the start of fixation Fi+1 as
%   the reference time. Scan candidate TCP lags, compare the gaze direction
%   with TCP displacement over a fixed window, and retain the lag with the
%   maximum cosine similarity. Also calculate filtered planar TCP curvature
%   and sample it at every gaze-transition reference time.
%
% Inputs:
%   *_fixation_transitions.csv from
%   compute_plot_similarity_fixation_direction_force_vel.m.
%   Matching raw ur5e_fixed_adm_2d_*.csv with synchronized time_s and
%   CoppeliaSim x-y TCP position [m]. The raw file is inferred from trial_id
%   unless read_robot_csv_file is set explicitly.
%
% Outputs:
%   lead_lag_table in the workspace and a *_gaze_tcp_lead_lag.csv file in
%   data/processed_data. lag_similarity_matrix contains S_i(tau) for every
%   transition and scanned lag. Three figures show the lag scan, temporal
%   results/curvature, and spatial leader/follower locations. Inputs are not
%   modified.
%
% Sign convention:
%   tau_star > synchronous_lag_tolerance_s  -> gaze leads TCP
%   tau_star < -synchronous_lag_tolerance_s -> TCP leads gaze
%   otherwise                               -> approximately synchronous
%
% Frames and units:
%   Gaze transition and TCP displacement are both in CoppeliaSim x-y [m].
%   Time and lag are [s], similarity is unitless, and curvature is [1/m].

clear;
close all;
clc;

%% User Settings
script_directory = fileparts(mfilename('fullpath'));

% TODO Select the fixation-transition CSV to analyze.
read_transition_csv_file = fullfile( ...
    script_directory, '..', 'data', 'processed_data', ...
    'ur5e_fixed_adm_2d_sym_random_shape_intentional_gaze_lead_d10_fixation_transitions.csv');

% TODO Optionally set the matching raw robot CSV. Leave empty to infer
% data/raw_data/<trial_id>.csv from the transition table.
read_robot_csv_file = "";

% TODO Optionally set the output CSV. Leave empty to write
% data/processed_data/<trial_id>_gaze_tcp_lead_lag.csv.
write_lead_lag_csv_file = "";

% TODO TCP lag scan [s]. Recommended range: -2 to +2 s with a step of
% 0.01 to 0.05 s. Positive tau means the matching TCP motion occurs later.
tcp_lag_values_s = -1.0:0.02:1.0;

% TODO Forward TCP-displacement window W [s]. Recommended: 0.1 to 1.0 s.
tcp_displacement_window_s = 0.4;

% TODO Minimum gaze displacement [m]. Recommended: 0.0005 to 0.005 m.
minimum_gaze_displacement_m = 0.001;

% TODO Minimum TCP displacement over W [m]. Recommended: 0.0005 to 0.005 m.
minimum_tcp_displacement_m = 0.001;

% TODO Absolute lag treated as approximately synchronous [s]. Recommended:
% zero to two lag-grid steps. This affects only the categorical label.
synchronous_lag_tolerance_s = 0.04;

% TODO Moving-median window for TCP position outliers [s]. Recommended:
% 0.005 to 0.050 s. Set to zero to disable this stage.
tcp_position_outlier_window_s = 0.02;

% TODO Symmetric moving-mean window before differentiation [s]. Recommended:
% 0.03 to 0.20 s. Larger values suppress noise but round sharp corners.
tcp_position_smoothing_window_s = 0.08;

% TODO Curvature is undefined below this filtered TCP speed [m/s].
% Recommended: 0.001 to 0.02 m/s, depending on trajectory speed/noise.
minimum_curvature_speed_m_s = 0.002;

% TODO Show every Nth fixation-transition label on the spatial plot [count].
% Recommended: 1 to 5; use 1 to label every transition.
transition_label_stride = 1;

%% Validate settings
tcp_lag_values_s = double(tcp_lag_values_s(:)');
if isempty(tcp_lag_values_s) || ...
        any(~isfinite(tcp_lag_values_s)) || ...
        any(diff(tcp_lag_values_s) <= 0)
    error('tcp_lag_values_s must be a finite, strictly increasing vector.');
end
if tcp_displacement_window_s <= 0
    error('tcp_displacement_window_s must be positive.');
end
if minimum_gaze_displacement_m < 0 || minimum_tcp_displacement_m < 0
    error('Displacement thresholds cannot be negative.');
end
if synchronous_lag_tolerance_s < 0
    error('synchronous_lag_tolerance_s cannot be negative.');
end
if tcp_position_outlier_window_s < 0 || ...
        tcp_position_smoothing_window_s <= 0
    error('TCP filter windows must be nonnegative, with smoothing > 0.');
end
if minimum_curvature_speed_m_s <= 0
    error('minimum_curvature_speed_m_s must be positive.');
end
if transition_label_stride < 1 || ...
        transition_label_stride ~= floor(transition_label_stride)
    error('transition_label_stride must be a positive integer.');
end

%% Load fixation transitions and resolve related files
if ~isfile(read_transition_csv_file)
    error('Transition CSV not found: %s', read_transition_csv_file);
end

transition_table = readtable( ...
    read_transition_csv_file, ...
    'Delimiter', ',', ...
    'ReadVariableNames', true, ...
    'VariableNamingRule', 'preserve', ...
    'TextType', 'string');

required_transition_variables = {
    'trial_id'
    'transition_index'
    'from_fixation'
    'to_fixation'
    'end_time_s'
    'robot_end_time_s'
    'gaze_dx_m'
    'gaze_dy_m'
    };
require_table_variables( ...
    transition_table, ...
    required_transition_variables, ...
    'fixation-transition CSV');

trial_ids = unique(strtrim(string(transition_table.trial_id)));
trial_ids = trial_ids(~ismissing(trial_ids) & strlength(trial_ids) > 0);
if numel(trial_ids) ~= 1
    error('The transition CSV must contain exactly one nonempty trial_id.');
end
trial_id = trial_ids(1);

if strlength(string(read_robot_csv_file)) == 0
    read_robot_csv_file = fullfile( ...
        script_directory, '..', 'data', 'raw_data', trial_id + ".csv");
end
if ~isfile(read_robot_csv_file)
    error('Matching raw robot CSV not found: %s', read_robot_csv_file);
end

if strlength(string(write_lead_lag_csv_file)) == 0
    write_lead_lag_csv_file = fullfile( ...
        script_directory, '..', 'data', 'processed_data', ...
        trial_id + "_gaze_tcp_lead_lag.csv");
end

%% Load and filter the raw CoppeliaSim TCP trajectory
robot_table = readtable( ...
    read_robot_csv_file, ...
    'Delimiter', ',', ...
    'ReadVariableNames', true, ...
    'VariableNamingRule', 'preserve', ...
    'TextType', 'string');

required_robot_variables = {
    'time_s'
    'coppeliasim_x_m'
    'coppeliasim_y_m'
    };
require_table_variables( ...
    robot_table, required_robot_variables, 'raw robot CSV');

robot_time_s = get_numeric_column(robot_table.time_s);
robot_x_coppelia_m = get_numeric_column(robot_table.coppeliasim_x_m);
robot_y_coppelia_m = get_numeric_column(robot_table.coppeliasim_y_m);

tcp = prepare_tcp_trajectory( ...
    robot_time_s, ...
    robot_x_coppelia_m, ...
    robot_y_coppelia_m, ...
    tcp_position_outlier_window_s, ...
    tcp_position_smoothing_window_s, ...
    minimum_curvature_speed_m_s);

%% Extract gaze transitions and their reference times
transition_count = height(transition_table);
lag_count = numel(tcp_lag_values_s);

transition_index = get_numeric_column( ...
    transition_table.transition_index);
from_fixation = get_numeric_column(transition_table.from_fixation);
to_fixation = get_numeric_column(transition_table.to_fixation);

% end_time_s is the start time of fixation Fi+1 in the synchronized gaze
% timeline. robot_end_time_s is that same event mapped to the robot timeline.
gaze_reference_time_s = get_numeric_column(transition_table.end_time_s);
tcp_reference_time_s = get_numeric_column( ...
    transition_table.robot_end_time_s);

gaze_dx_m = get_numeric_column(transition_table.gaze_dx_m);
gaze_dy_m = get_numeric_column(transition_table.gaze_dy_m);
gaze_displacement_m = hypot(gaze_dx_m, gaze_dy_m);

gaze_unit_x = NaN(transition_count, 1);
gaze_unit_y = NaN(transition_count, 1);
valid_gaze_displacement = ...
    isfinite(gaze_displacement_m) & ...
    gaze_displacement_m >= minimum_gaze_displacement_m;
gaze_unit_x(valid_gaze_displacement) = ...
    gaze_dx_m(valid_gaze_displacement) ./ ...
    gaze_displacement_m(valid_gaze_displacement);
gaze_unit_y(valid_gaze_displacement) = ...
    gaze_dy_m(valid_gaze_displacement) ./ ...
    gaze_displacement_m(valid_gaze_displacement);

reference_tcp_x_m = interpolate_without_extrapolation( ...
    tcp.time_s, tcp.x_filtered_m, tcp_reference_time_s);
reference_tcp_y_m = interpolate_without_extrapolation( ...
    tcp.time_s, tcp.y_filtered_m, tcp_reference_time_s);
reference_tcp_speed_m_s = interpolate_without_extrapolation( ...
    tcp.time_s, tcp.speed_m_s, tcp_reference_time_s);
reference_tcp_curvature_1_m = interpolate_without_extrapolation( ...
    tcp.time_s, tcp.curvature_1_m, tcp_reference_time_s);
reference_tcp_signed_curvature_1_m = ...
    interpolate_without_extrapolation( ...
    tcp.time_s, tcp.signed_curvature_1_m, tcp_reference_time_s);

%% Scan TCP lag for every fixation transition
lag_similarity_matrix = NaN(transition_count, lag_count);
tau_star_s = NaN(transition_count, 1);
maximum_similarity = NaN(transition_count, 1);
maximum_similarity_angle_deg = NaN(transition_count, 1);
valid_lag_count = zeros(transition_count, 1);
peak_at_lag_boundary = false(transition_count, 1);

best_tcp_window_start_time_s = NaN(transition_count, 1);
best_tcp_window_end_time_s = NaN(transition_count, 1);
best_tcp_dx_m = NaN(transition_count, 1);
best_tcp_dy_m = NaN(transition_count, 1);
best_tcp_displacement_m = NaN(transition_count, 1);
best_tcp_unit_x = NaN(transition_count, 1);
best_tcp_unit_y = NaN(transition_count, 1);

leader_follower = repmat("rejected", transition_count, 1);
analysis_valid = false(transition_count, 1);
analysis_status = repmat("not_evaluated", transition_count, 1);

for transition_idx = 1:transition_count
    if ~isfinite(tcp_reference_time_s(transition_idx))
        analysis_status(transition_idx) = "invalid_reference_time";
        continue;
    end

    if ~valid_gaze_displacement(transition_idx)
        analysis_status(transition_idx) = ...
            "gaze_displacement_below_threshold";
        continue;
    end

    tcp_window_start_times_s = ...
        tcp_reference_time_s(transition_idx) + tcp_lag_values_s;
    tcp_window_end_times_s = ...
        tcp_window_start_times_s + tcp_displacement_window_s;

    tcp_start_x_m = interpolate_without_extrapolation( ...
        tcp.time_s, tcp.x_filtered_m, tcp_window_start_times_s);
    tcp_start_y_m = interpolate_without_extrapolation( ...
        tcp.time_s, tcp.y_filtered_m, tcp_window_start_times_s);
    tcp_end_x_m = interpolate_without_extrapolation( ...
        tcp.time_s, tcp.x_filtered_m, tcp_window_end_times_s);
    tcp_end_y_m = interpolate_without_extrapolation( ...
        tcp.time_s, tcp.y_filtered_m, tcp_window_end_times_s);

    tcp_dx_by_lag_m = tcp_end_x_m - tcp_start_x_m;
    tcp_dy_by_lag_m = tcp_end_y_m - tcp_start_y_m;
    tcp_displacement_by_lag_m = hypot( ...
        tcp_dx_by_lag_m, tcp_dy_by_lag_m);

    valid_tcp_lag = ...
        isfinite(tcp_dx_by_lag_m) & ...
        isfinite(tcp_dy_by_lag_m) & ...
        tcp_displacement_by_lag_m >= minimum_tcp_displacement_m;
    valid_lag_count(transition_idx) = nnz(valid_tcp_lag);

    similarity_by_lag = NaN(1, lag_count);
    similarity_by_lag(valid_tcp_lag) = ...
        gaze_unit_x(transition_idx) .* ...
        tcp_dx_by_lag_m(valid_tcp_lag) ./ ...
        tcp_displacement_by_lag_m(valid_tcp_lag) + ...
        gaze_unit_y(transition_idx) .* ...
        tcp_dy_by_lag_m(valid_tcp_lag) ./ ...
        tcp_displacement_by_lag_m(valid_tcp_lag);
    similarity_by_lag(valid_tcp_lag) = max( ...
        -1.0, min(1.0, similarity_by_lag(valid_tcp_lag)));
    lag_similarity_matrix(transition_idx, :) = similarity_by_lag;

    finite_lag_indices = find(isfinite(similarity_by_lag));
    if isempty(finite_lag_indices)
        analysis_status(transition_idx) = ...
            "no_tcp_displacement_above_threshold";
        continue;
    end

    peak_similarity = max(similarity_by_lag(finite_lag_indices));

    % Avoid a negative-lag bias when several grid points have the same
    % numerical maximum: among tied maxima, retain the lag closest to zero.
    tie_tolerance = 100.0 * eps(max(1.0, abs(peak_similarity)));
    tied_lag_indices = finite_lag_indices( ...
        abs(similarity_by_lag(finite_lag_indices) - ...
        peak_similarity) <= tie_tolerance);
    [~, closest_to_zero_idx] = min( ...
        abs(tcp_lag_values_s(tied_lag_indices)));
    best_lag_idx = tied_lag_indices(closest_to_zero_idx);

    tau_star_s(transition_idx) = tcp_lag_values_s(best_lag_idx);
    maximum_similarity(transition_idx) = ...
        similarity_by_lag(best_lag_idx);
    maximum_similarity_angle_deg(transition_idx) = acosd( ...
        maximum_similarity(transition_idx));
    peak_at_lag_boundary(transition_idx) = ...
        best_lag_idx == 1 || best_lag_idx == lag_count;

    best_tcp_window_start_time_s(transition_idx) = ...
        tcp_window_start_times_s(best_lag_idx);
    best_tcp_window_end_time_s(transition_idx) = ...
        tcp_window_end_times_s(best_lag_idx);
    best_tcp_dx_m(transition_idx) = tcp_dx_by_lag_m(best_lag_idx);
    best_tcp_dy_m(transition_idx) = tcp_dy_by_lag_m(best_lag_idx);
    best_tcp_displacement_m(transition_idx) = ...
        tcp_displacement_by_lag_m(best_lag_idx);
    best_tcp_unit_x(transition_idx) = ...
        best_tcp_dx_m(transition_idx) / ...
        best_tcp_displacement_m(transition_idx);
    best_tcp_unit_y(transition_idx) = ...
        best_tcp_dy_m(transition_idx) / ...
        best_tcp_displacement_m(transition_idx);

    if tau_star_s(transition_idx) > synchronous_lag_tolerance_s
        leader_follower(transition_idx) = "gaze_leads_tcp";
    elseif tau_star_s(transition_idx) < -synchronous_lag_tolerance_s
        leader_follower(transition_idx) = "tcp_leads_gaze";
    else
        leader_follower(transition_idx) = ...
            "approximately_synchronous";
    end

    analysis_valid(transition_idx) = true;
    analysis_status(transition_idx) = "accepted";
end

