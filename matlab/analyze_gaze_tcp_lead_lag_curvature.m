function require_table_variables(data_table, required_variables, table_name)
%REQUIRE_TABLE_VARIABLES Verify that a table contains required columns.

    imported_variables = data_table.Properties.VariableNames;
    missing_variables = setdiff(required_variables, imported_variables);
    if ~isempty(missing_variables)
        error('%s is missing required columns: %s', ...
            table_name, strjoin(missing_variables, ', '));
    end
end

function numeric_values = get_numeric_column(raw_values)
%GET_NUMERIC_COLUMN Convert a table column to a numeric column vector.

    if isnumeric(raw_values) || islogical(raw_values)
        numeric_values = double(raw_values(:));
    else
        numeric_values = str2double(string(raw_values(:)));
    end
end

function interpolated_values = interpolate_without_extrapolation( ...
        sample_time_s, sample_values, query_time_s)
%INTERPOLATE_WITHOUT_EXTRAPOLATION Linearly interpolate only within data.
%
% Input:
%   sample_time_s - strictly increasing sample times [s].
%   sample_values - sampled scalar signal.
%   query_time_s  - scalar/vector query times [s].
%
% Output:
%   interpolated_values - query values; NaN outside the recorded interval.

    interpolated_values = interp1( ...
        sample_time_s, sample_values, query_time_s, 'linear', NaN);
end

function tcp = prepare_tcp_trajectory( ...
        raw_time_s, ...
        raw_x_m, ...
        raw_y_m, ...
        outlier_window_s, ...
        smoothing_window_s, ...
        minimum_speed_m_s)
%PREPARE_TCP_TRAJECTORY Filter TCP position and calculate planar curvature.
%
% Input:
%   raw_time_s          - raw synchronized robot time [s].
%   raw_x_m, raw_y_m    - CoppeliaSim-frame TCP position [m].
%   outlier_window_s    - moving-median position window [s].
%   smoothing_window_s  - moving-mean position/velocity window [s].
%   minimum_speed_m_s   - speed below which curvature is undefined [m/s].
%
% Output:
%   tcp - structure containing uniformly sampled filtered position, speed,
%         signed curvature, and curvature magnitude.
%
% Method:
%   Remove invalid/duplicate samples, interpolate onto a uniform grid, apply
%   symmetric moving-median and moving-mean filters, then use centered
%   numerical gradients. Curvature is
%   kappa = (vx*ay - vy*ax)/(vx^2 + vy^2)^(3/2).

    valid_rows = ...
        isfinite(raw_time_s) & isfinite(raw_x_m) & isfinite(raw_y_m);
    clean_time_s = raw_time_s(valid_rows);
    clean_x_m = raw_x_m(valid_rows);
    clean_y_m = raw_y_m(valid_rows);

    if numel(clean_time_s) < 5
        error('The raw robot CSV has too few valid TCP samples.');
    end

    [clean_time_s, sort_order] = sort(clean_time_s);
    clean_x_m = clean_x_m(sort_order);
    clean_y_m = clean_y_m(sort_order);

    [clean_time_s, unique_indices] = unique(clean_time_s, 'stable');
    clean_x_m = clean_x_m(unique_indices);
    clean_y_m = clean_y_m(unique_indices);

    sample_intervals_s = diff(clean_time_s);
    sample_intervals_s = sample_intervals_s(sample_intervals_s > 0);
    if isempty(sample_intervals_s)
        error('The raw robot time column is not strictly increasing.');
    end
    median_interval_s = median(sample_intervals_s);

    uniform_time_s = ( ...
        clean_time_s(1):median_interval_s:clean_time_s(end))';
    if numel(uniform_time_s) < 5
        error('The uniformly resampled TCP trajectory is too short.');
    end

    uniform_x_m = interp1( ...
        clean_time_s, clean_x_m, uniform_time_s, 'linear');
    uniform_y_m = interp1( ...
        clean_time_s, clean_y_m, uniform_time_s, 'linear');

    outlier_sample_count = window_to_odd_sample_count( ...
        outlier_window_s, median_interval_s, numel(uniform_time_s));
    smoothing_sample_count = window_to_odd_sample_count( ...
        smoothing_window_s, median_interval_s, numel(uniform_time_s));

    if outlier_sample_count > 1
        filtered_x_m = movmedian( ...
            uniform_x_m, outlier_sample_count, 'Endpoints', 'shrink');
        filtered_y_m = movmedian( ...
            uniform_y_m, outlier_sample_count, 'Endpoints', 'shrink');
    else
        filtered_x_m = uniform_x_m;
        filtered_y_m = uniform_y_m;
    end

    filtered_x_m = movmean( ...
        filtered_x_m, smoothing_sample_count, 'Endpoints', 'shrink');
    filtered_y_m = movmean( ...
        filtered_y_m, smoothing_sample_count, 'Endpoints', 'shrink');

    velocity_x_m_s = gradient(filtered_x_m, uniform_time_s);
    velocity_y_m_s = gradient(filtered_y_m, uniform_time_s);

    % A second symmetric smoothing pass limits noise amplification before
    % differentiating velocity to obtain acceleration.
    velocity_x_m_s = movmean( ...
        velocity_x_m_s, smoothing_sample_count, 'Endpoints', 'shrink');
    velocity_y_m_s = movmean( ...
        velocity_y_m_s, smoothing_sample_count, 'Endpoints', 'shrink');

    acceleration_x_m_s2 = gradient(velocity_x_m_s, uniform_time_s);
    acceleration_y_m_s2 = gradient(velocity_y_m_s, uniform_time_s);
    speed_m_s = hypot(velocity_x_m_s, velocity_y_m_s);

    signed_curvature_1_m = NaN(size(speed_m_s));
    valid_curvature = ...
        isfinite(speed_m_s) & speed_m_s >= minimum_speed_m_s;
    curvature_denominator = ( ...
        velocity_x_m_s.^2 + velocity_y_m_s.^2).^(3.0 / 2.0);
    signed_curvature_1_m(valid_curvature) = ( ...
        velocity_x_m_s(valid_curvature) .* ...
        acceleration_y_m_s2(valid_curvature) - ...
        velocity_y_m_s(valid_curvature) .* ...
        acceleration_x_m_s2(valid_curvature)) ./ ...
        curvature_denominator(valid_curvature);

    tcp.time_s = uniform_time_s;
    tcp.x_filtered_m = filtered_x_m;
    tcp.y_filtered_m = filtered_y_m;
    tcp.velocity_x_m_s = velocity_x_m_s;
    tcp.velocity_y_m_s = velocity_y_m_s;
    tcp.speed_m_s = speed_m_s;
    tcp.signed_curvature_1_m = signed_curvature_1_m;
    tcp.curvature_1_m = abs(signed_curvature_1_m);
    tcp.sample_interval_s = median_interval_s;
    tcp.outlier_sample_count = outlier_sample_count;
    tcp.smoothing_sample_count = smoothing_sample_count;
end

function sample_count = window_to_odd_sample_count( ...
        window_s, sample_interval_s, maximum_sample_count)
%WINDOW_TO_ODD_SAMPLE_COUNT Convert a time window to an odd sample count.

    if window_s <= 0
        sample_count = 1;
        return;
    end

    sample_count = max(3, round(window_s / sample_interval_s));
    if mod(sample_count, 2) == 0
        sample_count = sample_count + 1;
    end

    largest_odd_count = maximum_sample_count;
    if mod(largest_odd_count, 2) == 0
        largest_odd_count = largest_odd_count - 1;
    end
    sample_count = min(sample_count, largest_odd_count);
end

function color_map = blue_white_red_colormap(color_count)
%BLUE_WHITE_RED_COLORMAP Return a diverging map for cosine similarity.

    color_count = max(3, round(color_count));
    lower_count = floor(color_count / 2);
    upper_count = color_count - lower_count;

    blue = [0.10, 0.30, 0.80];
    white = [1.00, 1.00, 1.00];
    red = [0.80, 0.15, 0.10];

    lower_map = [ ...
        linspace(blue(1), white(1), lower_count)', ...
        linspace(blue(2), white(2), lower_count)', ...
        linspace(blue(3), white(3), lower_count)'];
    upper_map = [ ...
        linspace(white(1), red(1), upper_count)', ...
        linspace(white(2), red(2), upper_count)', ...
        linspace(white(3), red(3), upper_count)'];
    color_map = [lower_map; upper_map];
end
