    'tcp_window_end_time_s', ...
    'tcp_dx_m', ...
    'tcp_dy_m', ...
    'tcp_displacement_m', ...
    'tcp_unit_x', ...
    'tcp_unit_y', ...
    'valid_lag_count', ...
    'peak_at_lag_boundary', ...
    'analysis_valid', ...
    'analysis_status', ...
    'tcp_displacement_window_s', ...
    'minimum_gaze_displacement_m', ...
    'minimum_tcp_displacement_m', ...
    'synchronous_lag_tolerance_s'});

write_output_directory = fileparts(write_lead_lag_csv_file);
